"""Curry Syntax Parser.
Constructs Module AST from token streams generated by the lexer.
"""

from typing import List, Optional, Any
from .lexer import Token, Lexer
from .ast import (
    Module, DataDecl, TypeDecl, FunctionDecl, DataConstructor,
    TypeExpr, FuncEquation, Pattern, VarPattern, ConstrPattern,
    LitPattern, WildcardPattern, Expr, VarExpr, LitExpr, AppExpr,
    ChoiceExpr, ConstraintExpr
)

class Parser:
    def __init__(self, tokens: List[Token]):
        self.tokens = tokens
        self.pos = 0

    def peek(self) -> Token:
        return self.tokens[self.pos]

    def consume(self, expected_type: Optional[str] = None) -> Token:
        tok = self.tokens[self.pos]
        if expected_type and tok.type != expected_type and tok.value != expected_type:
            raise SyntaxError(f"Expected {expected_type} but got {tok.type} '{tok.value}' at line {tok.line}:{tok.col}")
        if self.pos < len(self.tokens) - 1:
            self.pos += 1
        return tok

    def match(self, *types_or_vals: str) -> bool:
        tok = self.peek()
        return tok.type in types_or_vals or tok.value in types_or_vals

    def parse_module(self) -> Module:
        mod_name = "Main"
        imports = []
        decls = []

        # Optional 'module Name where'
        if self.match("module"):
            self.consume("module")
            mod_name = self.consume("IDENT").value
            while not self.match("where", "EOF"):
                self.consume()
            if self.match("where"):
                self.consume("where")

        while not self.match("EOF"):
            if self.match("import"):
                self.consume("import")
                import_name = self.consume("IDENT").value
                imports.append(import_name)
            elif self.match("data"):
                decls.append(self.parse_data_decl())
            elif self.match("type"):
                decls.append(self.parse_type_decl())
            elif self.match("IDENT"):
                decls.append(self.parse_function_decl())
            else:
                self.consume()

        return Module(name=mod_name, imports=imports, decls=decls)

    def parse_data_decl(self) -> DataDecl:
        self.consume("data")
        name = self.consume("IDENT").value
        type_params = []
        while self.match("IDENT") and self.peek().value[0].islower():
            type_params.append(self.consume("IDENT").value)

        constructors = []
        if self.match("EQUALS"):
            self.consume("EQUALS")
            while True:
                constr_name = self.consume("IDENT").value
                fields = []
                # Check for record syntax or positional types
                if self.match("{"):
                    self.consume("{")
                    while not self.match("}", "EOF"):
                        self.consume()
                    if self.match("}"):
                        self.consume("}")
                else:
                    while self.match("IDENT") and not self.match("PIPE", "deriving"):
                        fields.append(TypeExpr(name=self.consume("IDENT").value))
                constructors.append(DataConstructor(name=constr_name, fields=fields))
                if self.match("PIPE"):
                    self.consume("PIPE")
                else:
                    break

        # Optional deriving clause
        if self.match("deriving"):
            self.consume("deriving")
            while not self.match("EOF") and not self.match("data", "type", "import"):
                # Break on declaration boundary
                if self.match("IDENT") and self.peek().col == 1:
                    break
                self.consume()

        return DataDecl(name=name, type_params=type_params, constructors=constructors)

    def parse_type_decl(self) -> TypeDecl:
        self.consume("type")
        name = self.consume("IDENT").value
        self.consume("EQUALS")
        target_name = self.consume().value
        return TypeDecl(name=name, target=TypeExpr(name=target_name))

    def parse_function_decl(self) -> FunctionDecl:
        name = self.consume("IDENT").value
        type_sig = None

        if self.match("DOUBLE_COLON"):
            self.consume("DOUBLE_COLON")
            while not self.match("EOF") and not (self.match("IDENT") and self.peek().value == name):
                self.consume()
            if self.match("IDENT") and self.peek().value == name:
                self.consume("IDENT")

        patterns = []
        while not self.match("EQUALS", "PIPE", "EOF"):
            tok = self.consume()
            if tok.type == "IDENT":
                patterns.append(VarPattern(name=tok.value))
            elif tok.type == "NUMBER":
                patterns.append(LitPattern(value=float(tok.value) if '.' in tok.value else int(tok.value)))
            elif tok.type == "STRING":
                patterns.append(LitPattern(value=tok.value))

        rhs_expr = VarExpr(name="body")
        if self.match("EQUALS"):
            self.consume("EQUALS")
            # Consume until next declaration boundary at col 1
            body_toks = []
            while not self.match("EOF"):
                if self.peek().col == 1 and self.match("data", "type", "import", "IDENT"):
                    break
                body_toks.append(self.consume())
            rhs_expr = VarExpr(name=" ".join(t.value for t in body_toks))

        equation = FuncEquation(patterns=patterns, rhs=rhs_expr)
        return FunctionDecl(name=name, type_sig=type_sig, equations=[equation])
